// 深挖首句里与「哪段时间、问什么」有关的部分。健康检查、Top SQL 与 WDR 三页共用。
//
// 2026-10-19 测试抓到的两件事:
// ① 时段报告上点「深挖」,首句里没有时间段 —— 模型先按「最近 1 小时」「最近 24 小时」各跑了一遍才找对那一段。
//    所以首句一律带上评估窗口。
// ② 死锁那条发现的证据是写给用户看的(「把日志段贴给我」)。原样塞进用户的提问里,模型以为是用户让它去贴日志,
//    回了句「日志这两段我贴不了」,还去翻本机文件找日志。死锁类发现改成一句专门的问法,不搬证据原文。
//
// 之后用户又提:**所有**深挖入口都带上报告的时间。大盘上看的那份可能是几天前的(报告菜单、窗口历史都能切),
// 首句写「最近一次」,模型就去取现在的数,和用户眼前那份对不上。口径:
// · 有评估窗口的(时段体检、时段榜、WDR)带窗口,带秒(见 range.js windowPromptLabel);
// · 此刻巡检 / 累计榜带取数时间 MM-DD HH:MM,与页面上「巡检时间」「取数时间」是同一个 stamp。
// 每页一个「这份报告怎么称呼」的函数(pages/health.js hSrc、pages/topsql.js tSrc、pages/wdr.js wWhen),
// 各入口都从它拼,不各写各的。
// 「重新巡检 / 重新取数」是让模型重跑一次:有窗口的重跑同一个窗口;此刻巡检 / 累计榜只交代上一份是什么时候的、
// 供对比 —— 不让它去分析旧报告(它读不到旧报告,会去翻本机文件找)。

import { stamp } from './fmt.js';

export const DEADLOCK_CODES = new Set(['WIN_DEADLOCK', 'DEADLOCKS', 'WDR_DEADLOCK']);

/** when 形如「10-17 10:45 – 11:08 这段时间里」或「健康检查发现」;f 是那条发现。 */
export const deadlockPrompt = (when, f) => `请分析${when}的死锁(${f.metric}=${f.value})是哪几条语句造成的、谁被牺牲、怎么改。`
  + '死锁明细只在数据库日志里——先告诉我该取哪段时间的日志、怎么取;我把日志段贴给你之后,再用死锁日志解析给结论。';

/** 此刻巡检 / 累计榜的取数时间(存档时间戳 → MM-DD HH:MM);取不到返回 '',不写「—」进首句。 */
export const atText = (at) => (at ? stamp(at) : '');

/** 「重新巡检 / 重新取数」末尾那句:上一份是什么时候取的,供对比。取不到时间就不写。 */
export const prevNote = (at) => (atText(at) ? `上一份是 ${atText(at)} 的报告,供对比。` : '');
